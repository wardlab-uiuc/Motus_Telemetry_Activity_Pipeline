          stationary_min_valid_late,
        
        stationary_min_prop_within =
          stationary_min_prop_within,
        
        stationary_max_mean_abs_sigdif =
          stationary_max_mean_abs_sigdif,
        
        stationary_min_receiver_prop =
          stationary_min_receiver_prop
