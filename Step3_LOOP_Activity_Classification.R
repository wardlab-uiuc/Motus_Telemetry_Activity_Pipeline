# interval in seconds.

required_duty_cycle_col <- "Burst_Interval"


# Minimum fraction of expected transmission intervals required to retain an
# hourly activity estimate.
#
# Example:
# A 15-s transmitter produces approximately 240 expected detections per hour.
# At 0.25, an hour must contain at least 60 valid activity intervals.

sample_size_threshold <- 0.25


# Maximum timestamp difference used to identify detections belonging to the
# same transmitter burst.
#
# Multiple antennas or nearby receivers may record the same transmission at
# slightly different timestamps.

transmission_event_tolerance <- 0.3


# ------------------------------------------------------------------------------
# RECEIVER-SPECIFIC SIGNAL QUALITY
# ------------------------------------------------------------------------------

# Timing tolerance and minimum signal-to-noise ratio (SNR) used for each
# receiver type.
#
# These are the default values used in this study. Researchers applying the
# framework to other receiver systems may evaluate alternative values.

parameter_lookup <- tibble::tribble(
  ~DongleType_family, ~tolerance, ~S2N_cutoff,
  "FUNcube",                 0.3,           6,
  "RTL",                     0.3,          10,
  "SigmaEight",              0.3,          12
)


