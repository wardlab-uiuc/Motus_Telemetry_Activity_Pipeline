# Diel period used to evaluate extended inactivity.
#
# Choose ONE:
#
#   "day"
#     Use detections classified as day.
#     Appropriate when extended daytime inactivity would be unusual.
#
#   "night"
#     Use night_1 and night_2 detections.
#     Appropriate for primarily nocturnal species.
#
#   "all"
#     Use detections from all diel periods.
#
# Select a period during which the study species would normally be expected
# to show activity.

stationary_screen_timing <- "day"


# Number of hours preceding the final detection in the selected diel period
# used to evaluate extended inactivity.

stationary_late_window_hours <- 72


# Number of hours preceding the final detection in the selected diel period
# used to identify the focal receiver.

stationary_receiver_selection_hours <- 24


# Minimum number of valid signal-difference comparisons required within the
# screening window.

stationary_min_valid_late <- 30


# Minimum proportion of valid signal differences that must remain inside the
# receiver-specific inactivity threshold.

stationary_min_prop_within <- 0.80


# Maximum allowed mean absolute signal-strength difference, in dB.

stationary_max_mean_abs_sigdif <- 2.5


# Minimum proportion of detections in the receiver-selection window that must
# occur on the focal receiver.

stationary_min_receiver_prop <- 0.50


